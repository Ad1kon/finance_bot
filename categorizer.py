def detect_category(description: str, transaction_type: str = "expense") -> str:
    """Определяет категорию по тексту описания или возвращает 'Доход' для доходов."""
    if transaction_type == "income":
        return "Доход"

    text = description.lower()
    for category, keywords in CATEGORY_KEYWORDS.items():
        for kw in keywords:
            if kw in text:
                return category
    return "Прочее"


def normalize_category(category: str) -> str | None:
    """Нормализует название категории, возвращает None если категория не найдена."""
    normalized = category.strip()
    
    # Точное совпадение
    if normalized in CATEGORY_KEYWORDS or normalized in ("Доход", "Прочее"):
        return normalized
    
    # Поиск по lowercase
    lower = normalized.lower()
    for cat in CATEGORY_KEYWORDS.keys():
        if cat.lower() == lower:
            return cat
    
    # Проверка Доход и Прочее
    for cat in ("Доход", "Прочее"):
        if cat.lower() == lower:
            return cat
    
    return None


def all_categories() -> list[str]:
    return list(CATEGORY_KEYWORDS.keys()) + ["Доход", "Прочее"]
