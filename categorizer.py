def detect_category(description: str, transaction_type: str = "expense") -> str:
    """Определяет категорию по тексту описания или возвращает 'Доход' для доходов."""
    if transaction_type == "income":
        return "Доход"

    text = description.lower()
    for category, keywords in CATEGORY_KEYWORDS.items():
        for kw in keywords:
            if kw in text:
                return category
    return "Прочее"


def all_categories() -> list[str]:
    return list(CATEGORY_KEYWORDS.keys()) + ["Доход", "Прочее"]
